import { isCompilerInvariantFailure } from './compilerSourceEmission.js';
import { createCompilerGeneratedFileHeader } from './compilerGeneratedFileProvenance.js';

describe('createCompilerGeneratedFileHeader', () => {
  it('renders the complete input identity without retaining or changing caller data', () => {
    const moduleIdentity = {
      name: 'Value',
      packageName: '@flighthq/math',
      source: 'packages/math/src/value.ts',
    };
    const snapshot = structuredClone(moduleIdentity);

    expect(createCompilerGeneratedFileHeader(moduleIdentity, '//')).toBe(
      '// Generated by @flighthq/tool-compiler from @flighthq/math/packages/math/src/value.ts#Value. Do not edit.',
    );
    expect(moduleIdentity).toEqual(snapshot);
  });

  it('includes an exact validated upstream commit and target-elected comment prefix', () => {
    expect(
      createCompilerGeneratedFileHeader(
        { name: 'Value', packageName: '@flighthq/math', source: 'value.ts' },
        '#',
        '0123456789abcdef0123456789abcdef01234567',
      ),
    ).toBe(
      '# Generated by @flighthq/tool-compiler from @flighthq/math/value.ts#Value at 0123456789abcdef0123456789abcdef01234567. Do not edit.',
    );
  });

  it.each([
    {
      commentPrefix: '',
      moduleIdentity: { name: 'Value', packageName: '@flighthq/math', source: 'value.ts' },
      subject: '@flighthq/math/value.ts#Value',
      upstreamCommit: undefined,
    },
    {
      commentPrefix: '//\n',
      moduleIdentity: { name: 'Value', packageName: '@flighthq/math', source: 'value.ts' },
      subject: '@flighthq/math/value.ts#Value',
      upstreamCommit: undefined,
    },
    {
      commentPrefix: '//',
      moduleIdentity: { name: 'Value', packageName: '@flighthq/math', source: 'value\u2028.ts' },
      subject: '@flighthq/math/value\u2028.ts#Value',
      upstreamCommit: undefined,
    },
    {
      commentPrefix: '//',
      moduleIdentity: { name: 'Value', packageName: '@flighthq/math', source: 'value.ts' },
      subject: 'ABC',
      upstreamCommit: 'ABC',
    },
    {
      commentPrefix: '//',
      moduleIdentity: { name: 'Value', packageName: '@flighthq/math', source: 'value.ts' },
      subject: '0123456789abcdef0123456789abcdef0123456g',
      upstreamCommit: '0123456789abcdef0123456789abcdef0123456g',
    },
  ])(
    'refuses unsafe or incomplete provenance for $subject',
    ({ commentPrefix, moduleIdentity, subject, upstreamCommit }) => {
      try {
        createCompilerGeneratedFileHeader(moduleIdentity, commentPrefix, upstreamCommit);
        expect.unreachable('Expected invalid generated-file provenance to fail');
      } catch (error) {
        expect(isCompilerInvariantFailure(error)).toBe(true);
        expect(error).toMatchObject({
          code: 'invalid-generated-file-provenance',
          kind: 'compiler-invariant',
          name: 'CompilerInvariantError',
          subject,
        });
      }
    },
  );
});
